import React from "react";
import { RiskBadge } from "../components/RiskBadge";
import { StatusBadge } from "../components/StatusBadge";
import { ModeBadge } from "../components/ModeBadge";
import { EmptyState } from "../components/EmptyState";

export function ReportsPage({
  history = [],
  onSelectScan,
  onDownloadPdf,
  onNavigate,
}) {
  const eligibleReports = history.filter(
    (item) => item.scan_status === "complete" || item.scan_status === "blocked"
  );

  return (
    <div className="page-container reports-page">
      {/* 1. HEADER */}
      <div className="page-header-box">
        <h2>Audit Reports Library</h2>
        <p className="page-header-sub">
          Export formal, publication-ready PDF deceptive design audits generated by DarkShield AI.
        </p>
      </div>

      {/* 2. REPORTS GRID */}
      {eligibleReports.length === 0 ? (
        <section className="card">
          <EmptyState
            icon="📄"
            title="No PDF Reports Available"
            message="Run a website scan to generate an exportable PDF audit report."
            actionLabel="Scan a Website Now"
            onAction={() => onNavigate("scan")}
          />
        </section>
      ) : (
        <div className="reports-cards-grid">
          {eligibleReports.map((report) => {
            const isBlocked = report.scan_status === "blocked";
            return (
              <div key={report.scan_id} className="card report-item-card">
                <div className="report-card-top">
                  <div className="report-type-badge">
                    <span>{isBlocked ? "🛡️ Blocked Audit" : "📄 Deceptive Design Audit"}</span>
                  </div>
                  <StatusBadge status={report.scan_status} />
                </div>

                <div className="report-card-body">
                  <strong className="report-site-url" title={report.url}>
                    {report.url}
                  </strong>
                  <span className="report-site-title">{report.title || "Untitled Webpage"}</span>

                  <div className="report-meta-row">
                    <div className="meta-col">
                      <span className="meta-col-label">Risk Level:</span>
                      {isBlocked || report.scan_status === "partial" || report.dark_risk_score === null ? (
                        <RiskBadge level="Withheld" size="small" />
                      ) : (
                        <RiskBadge level={report.dark_risk_level || "None"} size="small" />
                      )}
                    </div>
                    <div className="meta-col">
                      <span className="meta-col-label">Patterns:</span>
                      <strong>{report.total_dark_patterns ?? 0} found</strong>
                    </div>
                    <div className="meta-col">
                      <span className="meta-col-label">Scan Mode:</span>
                      <ModeBadge mode={report.scan_mode} />
                    </div>
                  </div>

                  <div className="report-timestamp">
                    <span>Generated: {report.timestamp ? new Date(report.timestamp).toLocaleDateString(undefined, {
                      year: "numeric",
                      month: "short",
                      day: "numeric",
                      hour: "2-digit",
                      minute: "2-digit"
                    }) : "N/A"}</span>
                  </div>
                </div>

                <div className="report-card-actions">
                  <button
                    type="button"
                    className="btn-report-view"
                    onClick={() => onSelectScan(report.scan_id)}
                  >
                    <span>👁️ View Online</span>
                  </button>
                  <button
                    type="button"
                    className="btn-report-download"
                    onClick={() => onDownloadPdf(report.scan_id)}
                  >
                    <span>📥 Export PDF</span>
                  </button>
                </div>
              </div>
            );
          })}
        </div>
      )}
    </div>
  );
}
