"""
DarkShield AI - Access Block & Anti-Bot Detection Engine
========================================================

Identifies when automated browser access is denied by CDN/WAF security controls
(e.g., Akamai, Cloudflare, PerimeterX, Datadome, AWS WAF, or HTTP 403/401/429).

Guarantees:
- Never attempts to evade or bypass website protections.
- Detects block pages returning HTTP 200 via structural CDN signatures.
- Strictly prevents false positives on legitimate websites containing words
  like "security", "access", or "denied" in standard body copy.
"""

import re
from typing import Dict, Any, List, Optional


KNOWN_PROVIDERS = [
    ("Akamai", [
        r"errors\.edgesuite\.net",
        r"reference\s*#\s*[0-9a-f]{1,4}\.[0-9a-f]{4,16}\.[0-9a-f]{4,16}",
        r"reference\s*#\s*\d+\.[0-9a-f]+\.[0-9a-f]+",
        r"you don't have permission to access .* on this server",
        r"akamaighost",
        r"x-akamai-transformed",
        r"x-akamai-session-info"
    ]),
    ("Cloudflare", [
        r"cf-turnstile",
        r"cf-chl-bypass",
        r"attention required!\s*\|\s*cloudflare",
        r"checking your browser before accessing",
        r"just a moment\.\.\.",
        r"cloudflare ray id",
        r"id=\"cf-challenge-error-title\"",
        r"class=\"ray-id\"",
        r"error 1020\s+access denied",
        r"data-ray="
    ]),
    ("PerimeterX / HUMAN", [
        r"px-captcha",
        r"_pxappid",
        r"client\.perimeterx\.net",
        r"access to this page has been denied.*perimeterx",
        r"id=\"px-block\""
    ]),
    ("Datadome", [
        r"datadome",
        r"dd\.datadome\.co",
        r"captcha-delivery\.com",
        r"x-datadome"
    ]),
    ("AWS WAF / CloudFront", [
        r"403 error\s*-\s*the request could not be satisfied",
        r"generated by cloudfront \(cloudfront\)",
        r"x-amzn-waf-action",
        r"x-amz-cf-id",
        r"token\.awswaf\.com",
        r"awswafintegration",
        r"awswafcookiedomain",
        r"challenge-container",
        r"gokuprops"
    ]),
    ("Amazon Bot Control", [
        r"api-services-support@amazon\.com",
        r"to discuss automated access to amazon data",
        r"type the characters you see in this image",
        r"enter the characters you see below",
        r"sorry,\s*we just need to make sure you're not a robot"
    ])
]

# Explicit block phrases that indicate an access barrier
STRONG_BLOCK_PHRASES = [
    r"\baccess denied\b",
    r"\byou don't have permission to access\b",
    r"\bplease verify you are a human\b",
    r"\bverify that you are human\b",
    r"\bcomplete the captcha\b",
    r"\bconfirm you're not a robot\b",
    r"\bpardon our interruption\b",
    r"\bunusual traffic from your computer network\b",
    r"\b403 forbidden\b",
    r"\bsecurity check to continue\b"
]


class BlockDetectionResult(dict):
    """Dictionary supporting both mapping access and 3-tuple unpacking (is_blocked, provider, info)."""
    def __iter__(self):
        yield self.get("is_blocked", False)
        yield self.get("block_provider")
        yield self


def detect_access_block(
    page=None,
    response=None,
    html: str = "",
    title: str = "",
    text: str = "",
    status_code: int = 200,
    headers: Optional[Dict[str, str]] = None,
    url: str = "",
    http_status: Optional[int] = None,
    page_title: Optional[str] = None,
    body_text: Optional[str] = None,
) -> BlockDetectionResult:
    """
    Evaluates response metadata, DOM structure, headers, and content to determine
    if the page is an access denial, anti-bot challenge, or rate-limit page.

    Returns:
        BlockDetectionResult: Dict/tuple supporting both dict access and unpacking.
    """
    if http_status is not None:
        status_code = http_status
    if page_title is not None:
        title = page_title
    if body_text is not None:
        text = body_text

    evidence = []
    detected_provider = None
    block_type = None

    headers = headers or {}
    lower_headers = {k.lower(): str(v).lower() for k, v in headers.items()}
    lower_title = (title or "").lower().strip()
    lower_html = (html or "").lower()
    lower_text = (text or "").lower()
    combined_content = f"{lower_html} {lower_text}"

    # Extract headers evidence if response object is provided
    if response and not headers:
        try:
            resp_headers = response.all_headers()
            lower_headers = {k.lower(): str(v).lower() for k, v in resp_headers.items()}
            status_code = response.status
        except Exception:
            pass

    # 1. Identify specific CDN / WAF provider signatures
    for provider_name, patterns in KNOWN_PROVIDERS:
        for pat in patterns:
            # Check headers
            for h_k, h_v in lower_headers.items():
                if re.search(pat, h_k) or re.search(pat, h_v):
                    detected_provider = provider_name
                    evidence.append(f"Header match: {h_k}: {h_v[:80]}")
                    break
            if detected_provider:
                break

            # Check HTML & text
            match = re.search(pat, combined_content)
            if match:
                detected_provider = provider_name
                matched_snippet = combined_content[max(0, match.start() - 20):min(len(combined_content), match.end() + 30)].strip()
                evidence.append(f"Content signature ({provider_name}): '{matched_snippet[:90]}'")
                break
        if detected_provider:
            break

    # 2. Check HTTP status code
    if status_code in (403, 401, 429):
        if status_code == 403:
            block_type = "access_denied"
            evidence.append(f"HTTP 403 Forbidden")
        elif status_code == 401:
            block_type = "unauthorized"
            evidence.append(f"HTTP 401 Unauthorized")
        elif status_code == 429:
            block_type = "rate_limit"
            evidence.append(f"HTTP 429 Too Many Requests")
            if not detected_provider:
                detected_provider = "HTTP 429 Rate Limiting"

        return BlockDetectionResult({
            "is_blocked": True,
            "http_status": status_code,
            "block_provider": detected_provider or "Unknown security/CDN provider",
            "block_type": block_type,
            "reason": f"Website returned HTTP {status_code} ({block_type.replace('_', ' ').title()}). Automated scanning denied.",
            "evidence": evidence
        })

    # 3. Check for Provider-Confirmed Challenge on HTTP 200 / 202
    if detected_provider in ["Akamai", "Cloudflare", "PerimeterX", "Datadome", "AWS WAF / CloudFront", "Amazon Bot Control"]:
        # Verify it's actually an error or challenge, not just a site served through the CDN
        is_challenge = False
        if detected_provider == "Akamai" and ("reference #" in combined_content or "errors.edgesuite.net" in combined_content or "access denied" in combined_content):
            is_challenge = True
            block_type = "access_denied"
        elif detected_provider == "Cloudflare" and ("cf-turnstile" in combined_content or "attention required" in lower_title or "just a moment" in lower_title or "checking your browser" in combined_content):
            is_challenge = True
            block_type = "captcha_challenge"
        elif detected_provider == "PerimeterX / HUMAN" and ("px-captcha" in combined_content or "px-block" in combined_content or "access to this page has been denied" in combined_content):
            is_challenge = True
            block_type = "captcha_challenge"
        elif detected_provider == "Datadome" and ("captcha" in combined_content or "security check" in combined_content or "captcha-delivery" in combined_content or "verification" in lower_title):
            is_challenge = True
            block_type = "captcha_challenge"
        elif detected_provider == "AWS WAF / CloudFront" and (
            "403 error" in combined_content
            or "the request could not be satisfied" in combined_content
            or "token.awswaf.com" in combined_content
            or "awswafintegration" in combined_content
            or "challenge-container" in combined_content
            or status_code == 202
        ):
            is_challenge = True
            block_type = "waf_challenge"
        elif detected_provider == "Amazon Bot Control":
            is_challenge = True
            block_type = "bot_challenge"

        if is_challenge:
            return BlockDetectionResult({
                "is_blocked": True,
                "http_status": status_code,
                "block_provider": detected_provider,
                "block_type": block_type,
                "reason": f"Active {detected_provider} challenge/block page intercepted (HTTP {status_code}). Automated scanning denied.",
                "evidence": evidence
            })

    # 4. Check Page Title for Explicit Block Directives
    explicit_title_blocks = [
        "access denied",
        "403 forbidden",
        "forbidden",
        "attention required! | cloudflare",
        "just a moment...",
        "security check",
        "robot check",
        "pardon our interruption",
        "sorry! something went wrong!"
    ]
    for b_title in explicit_title_blocks:
        if lower_title == b_title or lower_title.startswith(b_title + " ") or lower_title.startswith(b_title + "-") or lower_title.startswith(b_title + ":") or b_title in lower_title:
            evidence.append(f"Title block signature: '{title}'")
            return BlockDetectionResult({
                "is_blocked": True,
                "http_status": status_code,
                "block_provider": detected_provider or "Unknown security/CDN provider",
                "block_type": "access_denied",
                "reason": f"Webpage title indicates access denial: '{title}'. Automated scanning denied.",
                "evidence": evidence
            })

    # 5. Short Error Pages with Strong Block Phrases (HTTP 200 or other)
    # A genuine block page usually has very sparse text (< 2500 characters)
    # A legitimate website article or policy page has substantial content (> 3000 characters).
    text_length = len(text.strip())
    if text_length < 2500 and text_length > 0:
        for phrase_pat in STRONG_BLOCK_PHRASES:
            m = re.search(phrase_pat, lower_text)
            if m:
                # Also verify page lacks substantial navigational links or article body
                evidence.append(f"Short error page text phrase: '{m.group(0)}' (length: {text_length} chars)")
                return BlockDetectionResult({
                    "is_blocked": True,
                    "http_status": status_code,
                    "block_provider": detected_provider or "Unknown security/CDN provider",
                    "block_type": "access_denied",
                    "reason": f"Sparse block page detected ({text_length} chars) with barrier phrasing. Automated scanning denied.",
                    "evidence": evidence
                })

    # 6. Not Blocked — Normal Accessible Webpage
    return BlockDetectionResult({
        "is_blocked": False,
        "http_status": status_code,
        "block_provider": None,
        "block_type": None,
        "reason": "Normal webpage content accessible for analysis.",
        "evidence": []
    })
